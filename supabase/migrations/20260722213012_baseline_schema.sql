CREATE TABLE IF NOT EXISTS "public"."drill_bit_models" (
    "id" bigint NOT NULL,
    "display_name" "text" NOT NULL,
    "nominal_size" "text" NOT NULL,
    "bit_type" "text" DEFAULT 'PDC'::"text" NOT NULL,
    "product_line" "text" DEFAULT ''::"text" NOT NULL,
    "iadc_code" "text" DEFAULT ''::"text" NOT NULL,
    "connection" "text" DEFAULT ''::"text" NOT NULL,
    "list_price" numeric(12,2) NOT NULL,
    "description" "text",
    "image_url" "text",
    "active" boolean DEFAULT true NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "sku" "text",
    "manufacturer_part_number" "text",
    "circulation_type" "text" DEFAULT 'standard'::"text" NOT NULL,
    "nominal_size_in" numeric(6,3),
    "connection_size_in" numeric(6,3),
    "connection_type" "text",
    "blade_count" integer,
    "cutter_count" integer,
    "body_material" "text",
    "manufacturer_specs" "jsonb" DEFAULT '{}'::"jsonb" NOT NULL,
    CONSTRAINT "drill_bit_models_blade_count_check" CHECK ((("blade_count" IS NULL) OR ("blade_count" > 0))),
    CONSTRAINT "drill_bit_models_circulation_type_check" CHECK (("circulation_type" = ANY (ARRAY['standard'::"text", 'reverse_circulation'::"text"]))),
    CONSTRAINT "drill_bit_models_connection_size_in_check" CHECK ((("connection_size_in" IS NULL) OR ("connection_size_in" > (0)::numeric))),
    CONSTRAINT "drill_bit_models_cutter_count_check" CHECK ((("cutter_count" IS NULL) OR ("cutter_count" > 0))),
    CONSTRAINT "drill_bit_models_list_price_check" CHECK (("list_price" >= (0)::numeric)),
    CONSTRAINT "drill_bit_models_nominal_size_in_check" CHECK ((("nominal_size_in" IS NULL) OR ("nominal_size_in" > (0)::numeric)))
);


ALTER TABLE "public"."drill_bit_models" OWNER TO "postgres";


ALTER TABLE "public"."drill_bit_models" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."drill_bit_models_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);



CREATE TABLE IF NOT EXISTS "public"."featured_items" (
    "id" "uuid" DEFAULT "extensions"."uuid_generate_v4"() NOT NULL,
    "type" "text" NOT NULL,
