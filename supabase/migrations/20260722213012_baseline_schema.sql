    "condition" "text" DEFAULT 'unknown'::"text" NOT NULL,
    "location" "text",
    "notes" "text",
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    CONSTRAINT "inventory_units_condition_check" CHECK (("condition" = ANY (ARRAY['unknown'::"text", 'new'::"text", 'used'::"text", 'remanufactured'::"text"]))),
    CONSTRAINT "inventory_units_status_check" CHECK (("status" = ANY (ARRAY['available'::"text", 'reserved'::"text", 'in_repair'::"text", 'sold'::"text", 'scrapped'::"text"])))
